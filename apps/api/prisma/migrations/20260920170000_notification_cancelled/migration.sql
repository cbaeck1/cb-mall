-- PRD.md 8.72절 U-3: "다시 받기"와 진행 중인 재시도의 충돌 해소
--
-- 배경: 8.18절은 재시도가 모두 소진되면 사용자가 화면에서 "다시 받기"를 누르도록 정했다.
--       그런데 **재시도가 아직 진행 중일 때** 누르면 ① outbox 행이 둘이 되고
--       ② 8.7절상 재설정 토큰은 1회용이라 새 토큰 발급이 **이전 토큰을 무효화**한다.
--       그대로 두면 진행 중이던 재시도가 **이미 죽은 토큰이 담긴 메일을 발송**한다.
--
-- 처리: 새 토큰 발급 시 같은 사용자·같은 템플릿의 PENDING 행을 CANCELLED로 전환한다.
--       8.72절 U-2의 "발송 직전 토큰 유효성 확인"과 중복되는 방어지만, 이쪽은 불필요한
--       ESP 호출과 실패 로그 자체를 없앤다.

ALTER TYPE "notification_status" ADD VALUE IF NOT EXISTS 'CANCELLED';

-- 참고(8.72절 U-1): next_retry_at 의 계산 기준이 바뀐다.
--   기존: now() + 지연  → Cron 1분 주기가 회차마다 누적되어 긴급 프로파일 총 14분이 최대 17분
--   변경: created_at + 누적 지연(절대 시각) → 누적되지 않고 마지막 시도가 최대 t+15로 수렴
-- 컬럼 구조는 그대로이고 애플리케이션의 계산식만 달라지므로 DDL 변경은 없다.
