-- PRD.md 8.71절 T-2: 뒤늦게 도착한 결제 웹훅과 30분 자동취소의 충돌 상태
--
-- 배경: 8.8절은 PENDING 주문을 30분 뒤 자동 취소하는데, 토스 웹훅은 우리 쪽 응답이 실패하면
--       **3일 19시간 동안 최대 7회** 재시도된다. 즉 웹훅이 자동취소보다 훨씬 늦게 도착할 수 있고,
--       그때 paymentKey로 재조회하면 "결제 DONE × 주문 CANCELLED" 조합이 나온다
--       — 고객은 돈을 냈는데 상품은 받지 못한 상태다.
--
-- 처리: 자동 환불도, 주문 자동 복구도 하지 않는다. 그 사이 상품이 판매중지·가격변경되었거나
--       쿠폰이 재사용되었을 수 있어 검증할 예외가 많고, 자동 판단이 틀리면 돈이 얽힌다.
--       발생 빈도가 낮아(30분 초과 지연) 수동 처리의 운영 부담도 작다.
--       → NEEDS_REVIEW로 표시하고 8.17절 긴급 프로파일로 관리자에게 즉시 알린다.
--
-- 주의: PostgreSQL 12+ 는 트랜잭션 안에서 ALTER TYPE ... ADD VALUE 를 허용하되,
--       **같은 트랜잭션에서 그 값을 사용하는 것은 금지**한다. 이 마이그레이션은 값 추가만 하고
--       사용하지 않으므로 안전하다. 이후 이 값을 쓰는 DML은 반드시 별도 마이그레이션에 둘 것.

ALTER TYPE "order_status" ADD VALUE IF NOT EXISTS 'NEEDS_REVIEW';
